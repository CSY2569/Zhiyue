import 'package:rbwa/src/rust/models/ai.dart';

/// One [AiConfig] builder shared by the AI widget tests and the Rust smoke
/// tests. Every field has a deterministic default; tests override only what
/// they exercise. Keeping this in one place prevents the two fixtures from
/// drifting as new config fields are added.
AiConfig testAiConfig({
  String baseUrl = 'http://mock/v1',
  String apiKey = 'mock-key',
  String textModel = 'mock-text',
  String visionModel = 'mock-vision',
  bool webSearchEnabled = false,
  bool searchUseBuiltin = false,
  String? searchBaseUrl,
  String? searchApiKey,
  String searchBuiltinProtocol = 'responses',
  String searchThirdPartyProtocol = 'bocha',
  int searchFetchPages = 0,
  bool includeBookHistory = true,
  bool enableReasoning = false,
  String reasoningEffort = 'medium',
  double temperature = 0.7,
  String apiProtocol = 'chat_completions',
  String promptTemplate = 'general',
  String customPrompt = '',
  List<CustomPrompt> customPrompts = const [],
  Map<String, String> templateOverrides = const {},
  bool embeddingEnabled = false,
  String? embeddingBaseUrl,
  String? embeddingApiKey,
  String embeddingModel = '',
  String? vectorDbUrl,
  String? vectorDbApiKey,
  String vectorDbCollection = '',
  String ocrMode = 'high_precision',
  List<String> translateCustomLangs = const [],
  bool modelSupportsVision = false,
}) =>
    AiConfig(
      baseUrl: baseUrl,
      apiKey: apiKey,
      textModel: textModel,
      visionModel: visionModel,
      visionBaseUrl: null,
      visionApiKey: null,
      translateTargetLang: '中文',
      translateCustomLangs: translateCustomLangs,
      modelSupportsVision: modelSupportsVision,
      webSearchEnabled: webSearchEnabled,
      searchUseBuiltin: searchUseBuiltin,
      searchBaseUrl: searchBaseUrl,
      searchApiKey: searchApiKey,
      searchBuiltinProtocol: searchBuiltinProtocol,
      searchThirdPartyProtocol: searchThirdPartyProtocol,
      searchFetchPages: searchFetchPages,
      ocrMode: ocrMode,
      includeBookHistory: includeBookHistory,
      enableReasoning: enableReasoning,
      reasoningEffort: reasoningEffort,
      temperature: temperature,
      apiProtocol: apiProtocol,
      promptTemplate: promptTemplate,
      customPrompt: customPrompt,
      customPrompts: customPrompts,
      templateOverrides: templateOverrides,
      embeddingEnabled: embeddingEnabled,
      embeddingBaseUrl: embeddingBaseUrl,
      embeddingApiKey: embeddingApiKey,
      embeddingModel: embeddingModel,
      vectorDbUrl: vectorDbUrl,
      vectorDbApiKey: vectorDbApiKey,
      vectorDbCollection: vectorDbCollection,
    );
